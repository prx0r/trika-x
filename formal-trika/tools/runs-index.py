#!/usr/bin/env python3
"""runs-index.py — generate the machine-receipt section of runs/INDEX.md.

Thon Ly's formal-abhidhamma generates runs/INDEX.md from run directories so
the record cannot drift. Ours derives from runs/runs.jsonl (the machine
receipts written by tools/record_run.py). The hand-written verdict table
above it stays hand-written (interpretive); this script owns only the
receipt table and the staleness check.

  python3 tools/runs-index.py           rewrite runs/INDEX.md receipt section
  python3 tools/runs-index.py --check   exit 1 if the receipt section is stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "runs"
JSONL = RUNS / "runs.jsonl"
INDEX = RUNS / "INDEX.md"
MARKER = "## Machine receipts (generated by tools/runs-index.py — never edit by hand)"


def receipts():
    rows = []
    if not JSONL.is_file():
        return rows
    for line in JSONL.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        h = r.get("harnesses", {})
        rows.append({
            "at": r.get("at", "?"),
            "rev": r.get("rev", "?"),
            "lean": (r.get("lean") or "?").split(",")[0].replace("Lean (version ", ""),
            "control": h.get("control", {}).get("exit", "?"),
            "recognition": h.get("recognition", {}).get("exit", "?"),
            "tc1": h.get("tc1", {}).get("exit", "?"),
        })
    return rows


def render(rows):
    lines = [MARKER, "",
             "| At (UTC) | Rev | Lean | control | recognition | tc1 |",
             "|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['at']} | `{r['rev'][:8]}` | {r['lean']} | "
                     f"{'OK' if r['control'] == 0 else 'FAIL'} | "
                     f"{'OK' if r['recognition'] == 0 else 'FAIL'} | "
                     f"{'OK' if r['tc1'] == 0 else 'FAIL'} |")
    if not rows:
        lines.append("| — | — | — | — | — | — |")
    lines.append("")
    lines.append("Exit 0 = all harnesses green at that rev. "
                 "Generated from runs/runs.jsonl; edit that file, never this table.")
    return "\n".join(lines) + "\n"


def main():
    rows = receipts()
    body = render(rows)
    text = INDEX.read_text(encoding="utf-8") if INDEX.is_file() else ""
    if MARKER in text:
        head = text[: text.index(MARKER)]
        new = head + body
    else:
        new = text.rstrip("\n") + "\n\n" + body
    if "--check" in sys.argv:
        stale = (not INDEX.is_file()) or INDEX.read_text(encoding="utf-8") != new
        if stale:
            print("runs/INDEX.md receipt section is STALE — run tools/runs-index.py")
        else:
            print("runs/INDEX.md receipt section is current")
        return 1 if stale else 0
    INDEX.write_text(new, encoding="utf-8")
    print(f"runs/INDEX.md receipt section: {len(rows)} receipts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
