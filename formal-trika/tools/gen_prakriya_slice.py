#!/usr/bin/env python3
"""gen_prakriya_slice.py — generate + check the structural certificate slice.

Reads svread's grammar pack (SVREAD env, default /root/svread), emits
formal-trika/control/PrakriyaSlice.lean: rule inventory + one Trace per
DERIVED entry with a prakriya, a wellFormed checker, one theorem per trace,
and mutant theorems proving the checker REJECTS corruption (a vacuous
checker makes the file fail to compile).

SCOPE, stated in the file header and the receipt: this certifies structural
well-formedness over the declared rule inventory. It does NOT prove the steps
follow from the Aṣṭādhyāyī — a rule inventory is not a derivation from
Pāṇinian grammar (EXTERNAL-STRATEGY §B).

  python3 formal-trika/tools/gen_prakriya_slice.py           # write .lean
  python3 formal-trika/tools/gen_prakriya_slice.py --run     # write + lean + receipt
  python3 formal-trika/tools/gen_prakriya_slice.py --check   # byte-identical
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent          # formal-trika/tools
TRIKA = HERE.parent                             # formal-trika
CONTROL = TRIKA / 'control'
LEAN_OUT = CONTROL / 'PrakriyaSlice.lean'
RECEIPT = CONTROL / 'PrakriyaSlice.receipt.json'
SVREAD = Path(os.environ.get('SVREAD', '/root/svread'))
PACK = SVREAD / 'data' / 'grammar' / 'wheel-pack.json'

SCOPE = ("structural well-formedness over the declared rule inventory "
         "(every cited sutra code in inventory, every step carries a result, "
         "no empty trace/surface). NOT a derivation from the Aṣṭādhyāyī; "
         "a rule inventory is not a proof of rule applicability.")


def _readable(p: Path) -> bool:
    try:
        return p.is_file()
    except OSError:
        return False


def lean_env() -> str:
    return str(Path.home() / '.elan' / 'bin')


def build_source(pack: dict) -> str:
    entries = [e for e in pack.get('entries', [])
               if e.get('status') == 'DERIVED' and e.get('prakriya')]
    entries.sort(key=lambda e: e['id'])
    codes = sorted({str(s['sutra']) for e in entries for s in e['prakriya']})
    inv = ',\n  '.join(json.dumps(c) for c in codes)

    out = []
    out.append('/-')
    out.append('  PrakriyaSlice.lean — structural certificate checking for')
    out.append('  svread wheel traces. GENERATED by tools/gen_prakriya_slice.py —')
    out.append('  do not edit by hand; regenerate instead.')
    out.append('')
    out.append('  SCOPE: ' + SCOPE)
    out.append('-/')
    out.append('namespace PrakriyaSlice')
    out.append('')
    out.append('/-- Every sutra code our traces are allowed to cite. -/')
    out.append(f'def inventory : List String := [\n  {inv}]')
    out.append('')
    out.append('structure Step where')
    out.append('  sutra : String')
    out.append('  after : String')
    out.append('  deriving Repr, DecidableEq')
    out.append('')
    out.append('structure Trace where')
    out.append('  pack_id : String')
    out.append('  surface : String')
    out.append('  steps : List Step')
    out.append('  deriving Repr')
    out.append('')
    out.append('/-- Structural well-formedness. Decidable, so `decide` closes theorems. -/')
    out.append('def wellFormed (t : Trace) : Bool :=')
    out.append('  !t.steps.isEmpty && !(t.surface = "") &&')
    out.append('  t.steps.all (fun s => inventory.contains s.sutra && !(s.after = ""))')
    out.append('')

    def esc(s: str) -> str:
        return json.dumps(str(s))  # JSON string escaping is Lean-safe here

    traces = []
    for i, e in enumerate(entries):
        steps = ', '.join(
            '{sutra := %s, after := %s}' % (esc(s['sutra']), esc(s.get('after') or ''))
            for s in e['prakriya'])
        name = f'tr_{i}'
        traces.append(name)
        out.append(f'/-- {e["id"]} — surface {e.get("iast", "")} -/')
        out.append(f'def {name} : Trace :=')
        out.append('  { pack_id := %s, surface := %s, steps := [%s] }'
                   % (esc(e['id']), esc(e.get('iast') or ''), steps))
        out.append(f'theorem {name}_ok : wellFormed {name} = true := by decide')
        out.append('')
    out.append(f'def allTraces : List Trace := [{", ".join(traces)}]')
    out.append('theorem all_ok : allTraces.all wellFormed = true := by decide')
    out.append('')
    out.append('-- Mutants: each isolates one conjunct of wellFormed. If the checker')
    out.append('-- were vacuous (always true) these theorems fail to compile.')
    out.append('def mutant_bad_sutra : Trace :=')
    out.append('  { pack_id := "mutant", surface := "x", steps := [{sutra := "99.99.99", after := "x"}] }')
    out.append('theorem mutant_bad_sutra_rejected : wellFormed mutant_bad_sutra = false := by decide')
    out.append('')
    out.append('def mutant_empty_after : Trace :=')
    out.append('  { pack_id := "mutant", surface := "x", steps := [{sutra := %s, after := ""}] }'
               % esc(codes[0] if codes else '1.1.1'))
    out.append('theorem mutant_empty_after_rejected : wellFormed mutant_empty_after = false := by decide')
    out.append('')
    out.append('def mutant_no_steps : Trace := { pack_id := "mutant", surface := "x", steps := [] }')
    out.append('theorem mutant_no_steps_rejected : wellFormed mutant_no_steps = false := by decide')
    out.append('')
    out.append('def mutant_empty_surface : Trace :=')
    out.append('  { pack_id := "mutant", surface := "", steps := [{sutra := %s, after := "x"}] }'
               % esc(codes[0] if codes else '1.1.1'))
    out.append('theorem mutant_empty_surface_rejected : wellFormed mutant_empty_surface = false := by decide')
    out.append('')
    out.append('end PrakriyaSlice')
    out.append('')
    return '\n'.join(out), len(entries), len(codes)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--run', action='store_true', help='write + lean + receipt')
    args = ap.parse_args()
    if not _readable(PACK):
        print(f'gen_prakriya_slice: pack missing at {PACK} (set SVREAD)',
              file=sys.stderr)
        return 1
    pack_bytes = PACK.read_bytes()
    pack = json.loads(pack_bytes.decode('utf-8'))
    src, n_traces, n_codes = build_source(pack)
    if args.check:
        if not _readable(LEAN_OUT) or LEAN_OUT.read_text(encoding='utf-8') != src:
            print('gen_prakriya_slice --check: PrakriyaSlice.lean differs or missing',
                  file=sys.stderr)
            return 1
        print(f'gen_prakriya_slice --check: GREEN ({n_traces} traces, {n_codes} codes)')
        return 0
    LEAN_OUT.write_text(src, encoding='utf-8')
    print(f'gen_prakriya_slice: wrote {LEAN_OUT.name} ({n_traces} traces, {n_codes} codes)')
    if not args.run:
        return 0
    lean = Path(lean_env()) / 'lean'
    if not lean.exists():
        print('gen_prakriya_slice: lean not found; file written, no receipt',
              file=sys.stderr)
        return 0  # file-only is a valid intermediate state
    env = dict(os.environ, PATH=lean_env() + os.pathsep + os.environ.get('PATH', ''))
    t0 = time.time()
    proc = subprocess.run([str(lean), str(LEAN_OUT)], capture_output=True,
                          text=True, env=env, cwd=str(CONTROL))
    el = time.time() - t0
    ver = subprocess.run([str(lean), '--version'], capture_output=True,
                         text=True, env=env).stdout.strip().splitlines()[0]
    ok = proc.returncode == 0
    receipt = {
        'format': 'svatantrya.lean-receipt/1',
        'tool': 'PrakriyaSlice.lean',
        'scope': SCOPE,
        'lean_version': ver,
        'command': f'lean {LEAN_OUT.name}',
        'file_sha256': hashlib.sha256(LEAN_OUT.read_bytes()).hexdigest(),
        'pack_sha256': hashlib.sha256(pack_bytes).hexdigest(),
        'traces': n_traces,
        'inventory_codes': n_codes,
        'exit_code': proc.returncode,
        'seconds': round(el, 3),
        'checked_at': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
        'stderr_tail': (proc.stderr or '')[-400:],
    }
    if not ok:
        RECEIPT.write_text(json.dumps(receipt, indent=2, sort_keys=True) + '\n',
                           encoding='utf-8')
        print(f'gen_prakriya_slice: LEAN FAILED ({proc.returncode}) — receipt records the failure',
              file=sys.stderr)
        print(proc.stderr[-2000:], file=sys.stderr)
        return 1
    RECEIPT.write_text(json.dumps(receipt, indent=2, sort_keys=True) + '\n',
                       encoding='utf-8')
    print(f'gen_prakriya_slice: lean OK in {el:.2f}s — receipt written '
          f'({n_traces} traces checked, {ver})')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
