#!/usr/bin/env python3
"""vocab.py — the VOCABULARY of the formalization and nothing else.

Every `inductive` and `structure` across formal-trika (both namespaces,
mutants excluded), flattened into one namespace, with field-meaning
docstrings kept and file headers/row prose dropped. It is what a second,
BLIND encoder is given (see BLIND.md): enough types to write Lean over the
same categories, nothing of how the models combine them.

Usage: python3 tools/vocab.py [--check]
  (no flag rewrites formal-trika/Vocab.lean)
  --check exits 1 if Vocab.lean is stale (for CI).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Vocab.lean"
SOURCES = ["control/Mala.lean", "control/Pramatr.lean",
           "control/Kancuka.lean", "control/Recognition.lean",
           "control/AnswerKey.lean", "recognition/Transitions.lean",
           "recognition/NonEntail.lean", "recognition/Conjuncts.lean",
           "recognition/Memory.lean", "recognition/Tractatus.lean",
           "recognition/Coords.lean", "recognition/KancukaCorr.lean",
           "recognition/Grace.lean", "recognition/Upaya.lean"]


def strip(text):
    # drop file headers (/- ... -/, non-doc) and line comments;
    # keep docstrings (/-- ... -/): the field meanings.
    text = re.sub(r"/-(?!-).*?-/", "", text, flags=re.S)
    text = re.sub(r"(?m)^\s*--.*\n", "", text)
    return text


def blocks(text):
    out, cur, pending = [], None, []
    for line in text.split("\n"):
        s = line.strip()
        if s.startswith("/--") and s.rstrip().endswith("-/"):
            pending = [line]
            continue
        if re.match(r"^(inductive|structure) ", s):
            if cur:
                out.append("\n".join(cur))
            cur = pending + [line]
            pending = []
        elif cur is not None and (line.startswith((" ", "\t")) or s.startswith("|")):
            cur.append(line)
            pending = []
        elif cur is not None:
            if s == "":
                continue
            out.append("\n".join(cur))
            cur = None
    if cur:
        out.append("\n".join(cur))
    return out


def build():
    seen, chunks = set(), []
    for f in SOURCES:
        text = strip((ROOT / f).read_text(encoding="utf-8"))
        for b in blocks(text):
            m = re.search(r"(?m)^(?:inductive|structure) (\w+)", b)
            name = m.group(1)
            if name in seen:
                raise SystemExit(f"collision: {name} in {f} (prefix before flattening)")
            seen.add(name)
            body = re.sub(r"\n{2,}", "\n", b).rstrip()
            chunks.append(f"-- from {f}\n{body}")
    head = ["/-", "  Vocab.lean — GENERATED by tools/vocab.py: the types of the",
            "  formalization and nothing else (no definition of any row).",
            "  The vocabulary a second, blind encoder writes in. See BLIND.md.", "-/",
            "namespace V", ""]
    return "\n".join(head + chunks + ["", "end V", ""]) + "\n"


def main():
    want = build()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        print("Vocab.lean is current" if cur == want else
              "Vocab.lean is STALE — run tools/vocab.py")
        return 0 if cur == want else 1
    OUT.write_text(want, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} "
          f"({want.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
