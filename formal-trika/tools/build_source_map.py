#!/usr/bin/env python3
"""build_source_map.py — scaffold the 86-work chunk↔openpatala map (master step 1).

Reads every translation-work passages ledger (hash-pinned bytes), links the
6 formally-bridged works to their openpatala-map entries, and marks the
rest UNPINNED/CANDIDATE-TODO for the lane owner to resolve. Output path is
the plan-named location (svread/source-map.json); this tool is the
reproducible generator (re-run any time; diff the JSON).

Usage: python3 formal-trika/tools/build_source_map.py [--tw PATH] [--out PATH]
"""
import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
MAP = json.loads((HERE / "bridge" / "openpatala-map.json").read_text())

# ours-dir -> bridge work key for the 6 formally bridged works
BRIDGED = {"tantrasara-a08": "tsa08", "tantrasara-a07": "tsa07",
           "paramarthasara": "param", "phrdaya": "phr",
           "vbt": "vbt", "spanda": "spanda"}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tw", type=Path, default=HERE.parent.parent / "translation-work")
    ap.add_argument("--out", type=Path, default=HERE.parent.parent / "svread" / "source-map.json")
    a = ap.parse_args()
    works = {}
    for ledger in sorted(a.tw.glob("*/passages.jsonl")):
        workdir = ledger.parent.name
        sha = hashlib.sha256(ledger.read_bytes()).hexdigest()
        n = sum(1 for ln in ledger.read_text(encoding="utf-8").splitlines() if ln.strip())
        if workdir in BRIDGED:
            b = MAP["works"][BRIDGED[workdir]]
            works[workdir] = {"ledger": f"{workdir}/passages.jsonl",
                              "ledger_sha256": sha, "passages": n,
                              "openpatala_work_key": b["openpatala_work_key"],
                              "openpatala_work_id": b["openpatala_work_id"],
                              "witness": "UNPINNED", "status": b["status"]}
        else:
            works[workdir] = {"ledger": f"{workdir}/passages.jsonl",
                              "ledger_sha256": sha, "passages": n,
                              "openpatala_work_key": "UNRESOLVED",
                              "openpatala_work_id": "UNRESOLVED",
                              "witness": "UNPINNED", "status": "CANDIDATE-TODO"}
    doc = {"provenance": "Generated by formal-trika/tools/build_source_map.py from ledger bytes; 6 works bridged (see bridge/openpatala-map.json), rest await lane-owner resolution. Witnesses UNPINNED throughout.",
           "works": works}
    a.out.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    bridged = sum(1 for v in works.values() if v["status"] != "CANDIDATE-TODO")
    print(f"works: {len(works)} (bridged {bridged}, todo {len(works)-bridged}) -> {a.out}")


if __name__ == "__main__":
    raise SystemExit(main())
