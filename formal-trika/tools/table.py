#!/usr/bin/env python3
"""table.py — join hand readings with the sources into TABLE.md.

TABLE-READINGS.md is hand-written (one plain-English reading per theorem).
TABLE.md is GENERATED (never hand-edited): file :: theorem :: reading.
--check fails if any source theorem lacks a reading, any reading's theorem
vanished, or TABLE.md is stale. (Mirrors formal-abhidhamma's LISTS/TABLE
discipline at our scale: hand meaning, machine staleness.)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
READINGS = ROOT / "TABLE-READINGS.md"
OUT = ROOT / "TABLE.md"
SOURCES = ["control/Mala.lean", "control/Pramatr.lean",
           "control/Kancuka.lean", "control/Recognition.lean",
           "control/AnswerKey.lean", "control/Tattva.lean",
           "control/Avarana.lean", "control/MalaFuel.lean",
           "control/TattvaInventory.lean",
           "control/Pratyahara.lean", "control/Reversal.lean",
           "control/Nyasa.lean",
           "control/Embed.lean",
           "control/Ladder.lean",
           "control/TattvaGen.lean",
           "control/Prakasa.lean",
           "control/Spanda.lean",
           "control/Rasa.lean",
           "control/Phrdaya.lean",
           "control/Correction.lean",
           "frontier/Aperture.lean",
           "buddhist/Nanavira.lean",
           "frontier/Tetrahedron.lean",
           "frontier/Closure.lean",
           "recognition/Transitions.lean",
           "recognition/NonEntail.lean", "recognition/Conjuncts.lean",
           "recognition/Memory.lean", "recognition/Tractatus.lean",
           "recognition/Coords.lean", "recognition/KancukaCorr.lean",
           "recognition/Grace.lean", "recognition/Upaya.lean",
           "recognition/EgoOrigin.lean", "recognition/Heaps.lean",
           "recognition/Application.lean"]


def source_theorems():
    found = {}
    for f in SOURCES:
        text = (ROOT / f).read_text(encoding="utf-8")
        for m in re.finditer(r"(?m)^theorem\s+([A-Za-z0-9_]+)", text):
            from os.path import basename as _bn
            found.setdefault(m.group(1), []).append(_bn(f))
    return found


def readings():
    text = READINGS.read_text(encoding="utf-8")
    out = {}
    cur = None
    buf = []
    for line in text.split("\n"):
        m = re.match(r"^## (\S+) :: (\S+)\s*$", line)
        if m:
            if cur:
                out[cur] = "\n".join(buf).strip()
            cur = (m.group(1), m.group(2))
            buf = []
        elif cur is not None:
            buf.append(line)
    if cur:
        out[cur] = "\n".join(buf).strip()
    return out


def build():
    theorems = source_theorems()
    reads = readings()
    problems = []
    for name, files in sorted(theorems.items()):
        if len(files) > 1 or not any((f, name) in reads for f in files):
            if not any((f, name) in reads for f in files):
                problems.append(f"no reading for {name} ({', '.join(files)})")
    for (f, name) in reads:
        from os.path import basename as _bn
        if name not in theorems:
            problems.append(f"reading without theorem: {f} :: {name}")
        elif _bn(f) not in theorems[name]:
            problems.append(f"reading misfiled: {f} :: {name} "
                            f"(theorem lives in {theorems[name]})")
    n_theorems = sum(1 for f in SOURCES for _ in
                   re.finditer(r"(?m)^theorem\s+([A-Za-z0-9_]+)",
                               (ROOT / f).read_text(encoding="utf-8")))
    lines = ["# TABLE — every theorem beside its plain-English reading",
             "",
             "*GENERATED by `tools/table.py` from the Lean sources +",
             "`TABLE-READINGS.md` (hand readings); never edit by hand.",
             "A blind reader (BLIND.md) should understand each row without",
             f"reading the encoding. Rows: {n_theorems} theorems (incl. 2 scaffolds).*",
             "",
             "| File | Theorem | Reading |",
             "|---|---|---|"]
    from os.path import basename as _bn2
    for f in SOURCES:
        text = (ROOT / f).read_text(encoding="utf-8")
        for m in re.finditer(r"(?m)^theorem\s+([A-Za-z0-9_]+)", text):
            name = m.group(1)
            reading = reads.get((_bn2(f), name), "*MISSING*")
            first = reading.split("\n")[0] if reading else "*MISSING*"
            lines.append(f"| {f} | {name} | {first} |")
    return "\n".join(lines) + "\n", problems


def main():
    want, problems = build()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        stale = cur != want
        for p in problems:
            print("PROBLEM:", p)
        if stale:
            print("TABLE.md is STALE — run tools/table.py")
        return 1 if (problems or stale) else 0
    if problems:
        for p in problems:
            print("PROBLEM:", p)
        return 1
    OUT.write_text(want, encoding="utf-8")
    print(f"wrote TABLE.md ({want.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
